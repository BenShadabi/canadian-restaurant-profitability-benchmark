"""Load the CSVs into an in-memory SQLite database, run sql/queries.sql and write sql/results.md.
Run from the repo root:  python sql/run_queries.py        Requires: pandas, tabulate (sqlite3 is built in). Install with: pip install -r requirements.txt
"""
import re, sqlite3, pandas as pd
con = sqlite3.connect(":memory:")
for name, f in [("industry_trend", "industry_trend"), ("average_restaurant", "average_restaurant_2024"),
                ("wages", "wages_food_services"), ("restaurant_counts", "restaurant_counts_2024")]:
    pd.read_csv(f"data/{f}.csv").to_sql(name, con, index=False)
queries = [q.strip() for q in open("sql/queries.sql").read().split(";") if "SELECT" in q]
out = ["# Query results", "", "Generated by `sql/run_queries.py` from `sql/queries.sql`. Numbers come straight from the CSVs. Growth rates can differ slightly from the published ones because the CSV mixes release years (2022 was revised later, for example 24.7% here vs 24.3% in the 2022 release).", ""]
for q in queries:
    head = re.findall(r"(?m)^--\s*(.*)$", q)[-1]
    df = pd.read_sql_query(re.sub(r"(?m)^--.*\n", "", q), con)
    df = df.astype(object).where(df.notna(), "n/a")
    try:
        table = df.to_markdown(index=False)
    except ImportError:  # tabulate is not installed: fall back to plain text so the script still runs
        table = "```\n" + df.to_string(index=False) + "\n```"
    out += [f"## {head}", "", table, ""]
open("sql/results.md", "w").write("\n".join(out))
print(f"ran {len(queries)} queries, wrote sql/results.md")
